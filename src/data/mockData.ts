export function findOrCreateRestaurant(idOrQuery: string, assignedKam?: KAMUser): Restaurant | null {
  const clean = idOrQuery.trim().toUpperCase();
  const found = FEATURED_RESTAURANTS.find(
    (r) => r.id.toUpperCase() === clean || r.id.toUpperCase().includes(clean)
  );
  if (found) return found;

  // Match by name or chain
  const nameMatch = FEATURED_RESTAURANTS.find(
    (r) =>
      r.name.toLowerCase().includes(idOrQuery.toLowerCase()) ||
      r.chain.toLowerCase().includes(idOrQuery.toLowerCase()) ||
      r.zone.toLowerCase().includes(idOrQuery.toLowerCase()) ||
      r.city.toLowerCase().includes(idOrQuery.toLowerCase())
  );
  if (nameMatch) return nameMatch;

  // If user searched for arbitrary numeric ID e.g. "REST-10492" or "8421" or "REST-04521"
  const matchNum = clean.match(/(\d{3,5})/);
  if (matchNum) {
    const num = parseInt(matchNum[1], 10);
    const cities = ['Gurugram', 'Mumbai', 'Bengaluru', 'Delhi NCR', 'Hyderabad', 'Pune', 'Chennai', 'Kolkata'];
    const chains = [
      'Zomato Kitchens',
      'Biryani By Kilo',
      "Haldiram's",
      'Burger King India',
      'Chai Point',
      'Social Offline',
      'Behrouz Biryani',
      'Wow! Momo',
      'KFC India',
      'Faasos Cloud Kitchen',
      'Bikanervala',
      'Subway Fresh',
      'Dominos Cloud Hub',
    ];
    const cuisines = [
      'North Indian & Biryani',
      'Fast Food & Shakes',
      'Cloud Kitchen Aggregator',
      'Cafe & Breakfast',
      'Asian & Chinese',
      'South Indian Traditional',
    ];

    const city = cities[num % cities.length];
    const chain = chains[num % chains.length];
    const cuisine = cuisines[num % cuisines.length];
    const formattedId = `REST-${String(num).padStart(5, '0')}`;

    // Map to a KAM based on index or current KAM
    const kams = KAM_ROSTER.filter((k) => !k.isAdmin);
    const assigned = assignedKam && !assignedKam.isAdmin ? assignedKam : kams[num % kams.length];

    const totalOrders = 1100 + (num % 1200);
    const ordersVsLastYear = Math.round(totalOrders * 0.84);
    const aov = 2800 + (num % 900);
    const netRevLakhs = Number(((totalOrders * aov) / 1000000).toFixed(1));
    const revVsLastYearLakhs = Number((netRevLakhs * 0.82).toFixed(1));

    return {
      id: formattedId,
      name: `${chain} - Node #${num % 50 + 1} (${city})`,
      chain,
      city,
      zone: `Zone ${String.fromCharCode(65 + (num % 6))}-Sector ${num % 60 + 1}`,
      cuisine,
      status: (num % 5 === 0) ? 'Peak Surge' : 'Operational',
      kamId: assigned.id,
      kamName: assigned.name,
      kamEmail: assigned.email,
      totalOrdersYTD: totalOrders,
      ordersVsLastYear,
      ordersYoyDelta: `+${((totalOrders - ordersVsLastYear) / ordersVsLastYear * 100).toFixed(1)}%`,
      netRevenueLakhs: netRevLakhs,
      revenueVsLastYearLakhs: revVsLastYearLakhs,
      revenueYoyDelta: `+${((netRevLakhs - revVsLastYearLakhs) / revVsLastYearLakhs * 100).toFixed(1)}%`,
      aov,
      aovVsLastYear: aov - 110,
      aovYoyDelta: '+3.5%',
      fulfillmentRate: 98.2 + ((num % 15) / 10),
      slaMinutes: 18 + (num % 7),
      rating: 4.3 + ((num % 7) / 10),
      kitchenPrepTimeMinutes: 11 + (num % 8),
      cancellationRate: Number((0.3 + (num % 9) / 10).toFixed(1)),
      discountPercentage: Number((10 + (num % 12)).toFixed(1)),
      refundRate: Number((0.4 + (num % 8) / 10).toFixed(1)),
      onlineUptime: Number((98.8 + (num % 12) / 10).toFixed(1)),
      repeatCustomerRate: Number((40 + (num % 18)).toFixed(1)),
      adRoas: Number((3.8 + (num % 18) / 10).toFixed(1)),
      takeRateCommission: Number((16.5 + (num % 5)).toFixed(1)),
      riderWaitMinutes: Number((2.8 + (num % 25) / 10).toFixed(1)),
      npsScore: 70 + (num % 16),
      equipmentInstalled: ['Thermal Dispensers TD-45', 'Bulk Fleet Sensors'],
      monthlyChartData: GLOBAL_MONTHLY_DATA.map((pt) => ({
        ...pt,
        orders2025: Math.round(pt.orders2025 * (totalOrders / 13300)),
        orders2026: pt.orders2026 ? Math.round(pt.orders2026 * (totalOrders / 13300)) : null,
        ordersLabel2025: `${Math.round(pt.orders2025 * (totalOrders / 13300))}`,
        ordersLabel2026: pt.orders2026 ? `${Math.round(pt.orders2026 * (totalOrders / 13300))}` : undefined,
        revenue2025: Number((pt.revenue2025 * (netRevLakhs / 44.1)).toFixed(2)),
        revenue2026: pt.revenue2026 ? Number((pt.revenue2026 * (netRevLakhs / 44.1)).toFixed(2)) : null,
        revLabel2025: `₹${(pt.revenue2025 * (netRevLakhs / 44.1)).toFixed(2)}L`,
        revLabel2026: pt.revenue2026 ? `₹${(pt.revenue2026 * (netRevLakhs / 44.1)).toFixed(2)}L` : undefined,
      })),
    };
  }

  return null;
}

